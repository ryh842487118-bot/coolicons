/// Visual variants provided by the upstream Coolicons icon set.
enum CoolIconStyle {
  /// Stroke-based icon artwork.
  line,

  /// Stroke artwork with a secondary, lower-opacity stroke.
  duocolor,

  /// Stroke artwork with a low-opacity filled layer.
  duotone,

  /// Solid filled artwork.
  fill,

  /// Solid artwork with a lower-opacity layer.
  bulk,
}
